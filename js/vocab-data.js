// 開發用快速查詢函式
//
// Console 可輸入：
// findVocab("旅行")
// findVocab("りょこう")
// findVocab("ryokou")
// ============================================================

function findVocab(keyword) {

  const q = String(keyword || "").trim().toLowerCase();

  if (!q) return [];

  return vocabCategories
    .flatMap(category =>
      category.items.map(item => ({
        category: category.name,
        ...item
      }))
    )
    .filter(item =>
      [
        item.jp,
        item.read,
        item.romaji,
        item.zh,
        item.stJp,
        item.stRead,
        item.stZh
      ]
      .join(" ")
      .toLowerCase()
      .includes(q)
    );

}
