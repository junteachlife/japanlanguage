(() => {

  const all = vocabCategories.flatMap(category => category.items);

  const n5 = all.filter(item => item.level === "N5");
  const n4 = all.filter(item => item.level === "N4");

  const ids = new Set();
  const words = new Set();

  const duplicateIds = [];
  const duplicateWords = [];
  const incomplete = [];

  const required = [
    "id",
    "level",
    "jp",
    "read",
    "romaji",
    "zh",
    "stJp",
    "stRead",
    "stZh"
  ];

  all.forEach(item => {

    // ID 重複
    if (ids.has(item.id)) {
      duplicateIds.push(item.id);
    }
    ids.add(item.id);

    // 日文＋讀音重複
    const wordKey = `${item.jp}|${item.read}`;

    if (words.has(wordKey)) {
      duplicateWords.push(wordKey);
    }
    words.add(wordKey);

    // 欄位完整性
    if (
      required.some(key =>
        item[key] === undefined ||
        item[key] === null ||
        String(item[key]).trim() === ""
      )
    ) {
      incomplete.push(item.id);
    }

  });

  console.group("📚 JLPT N5・N4 詞彙資料庫");

  console.log(`📖 全部詞彙：${all.length}`);
  console.log(`🌱 N5：${n5.length}`);
  console.log(`🚀 N4：${n4.length}`);
  console.log(`🔍 不重複詞彙：${words.size}`);

  if (duplicateIds.length) {
    console.warn("⚠️ 發現重複 ID：", duplicateIds);
  } else {
    console.log("✅ ID 無重複");
  }

  if (duplicateWords.length) {
    console.warn("⚠️ 發現重複詞彙：", duplicateWords);
  } else {
    console.log("✅ 詞彙無重複");
  }

  if (incomplete.length) {
    console.warn("⚠️ 欄位不完整：", incomplete);
  } else {
    console.log("✅ 所有詞彙欄位完整");
  }

  console.log(
    `📊 N5 比例：${all.length ? Math.round(n5.length / all.length * 100) : 0}%`
  );

  console.log(
    `📊 N4 比例：${all.length ? Math.round(n4.length / all.length * 100) : 0}%`
  );

  console.groupEnd();

})();


// ============================================================
// 開發用快速查詢函式
//
// Console 可輸入：
// findVocab("旅行")
// findVocab("りょこう")
// findVocab("ryokou")
// ============================================================

function findVocab(keyword) {

  const q = String(keyword || "").trim().toLowerCase();

  if (!q) return [];

  return vocabCategories
    .flatMap(category =>
      category.items.map(item => ({
        category: category.name,
        ...item
      }))
    )
    .filter(item =>
      [
        item.jp,
        item.read,
        item.romaji,
        item.zh,
        item.stJp,
        item.stRead,
        item.stZh
      ]
      .join(" ")
      .toLowerCase()
      .includes(q)
    );

}
